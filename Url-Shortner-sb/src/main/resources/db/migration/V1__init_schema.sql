-- Baseline schema, matching what Hibernate previously generated via ddl-auto=update.
-- On a database that already has these tables (e.g. the existing Render instance),
-- Flyway is configured to baseline at this version instead of re-runningg it (see application.properties).

CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    email    VARCHAR(255) NOT NULL,
    role     VARCHAR(255) NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE url_mapping (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_url  VARCHAR(255) NOT NULL,
    short_url     VARCHAR(255) NOT NULL,
    click_count   INTEGER NOT NULL,
    created_date  TIMESTAMP NOT NULL,
    user_id       BIGINT,
    CONSTRAINT uq_url_mapping_short_url UNIQUE (short_url),
    CONSTRAINT fk_url_mapping_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE click_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    click_date      TIMESTAMP NOT NULL,
    url_mapping_id  BIGINT,
    CONSTRAINT fk_click_event_url_mapping FOREIGN KEY (url_mapping_id) REFERENCES url_mapping (id)
);
